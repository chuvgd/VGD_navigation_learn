#include <iostream>

//栈区数据注意事项：不要返回局部变量的地址
//栈区的数据由编译器管理开辟和释放

int* func(int b){//形参数据也会放在栈上
    b=100;
    int a=10;//局部变量
    //局部变量存放在栈区，栈区的数据在函数执行完后自动释放
    return &a;//返回局部变量的地址
}
//因为是局部变量，在执行完之后就会被直接释放
//执行一次函数体，则在栈区上开辟相关数据，在函数体运行结束之后，栈区自动释放相关数据

int main(){
    //接收func函数的返回值
    int* p=func(1);
    std::cout<<*p<<std::endl;//第一次可以打印正确的数据是编译器做了正确的保留
    std::cout<<*p<<std::endl;//第二次乱码，第二次就不保留了

    return 0;
}